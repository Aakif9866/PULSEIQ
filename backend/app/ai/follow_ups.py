"""Suggested next questions after an analysis: deterministic, built from
the dataset's real schema and the tools the answer actually used, so
each suggestion names real columns and is answerable by the tool layer.
Never generated by the LLM (no extra tokens, nothing invented)."""

from typing import Any

import polars as pl

from app.ai.tools import _auto_dimensions, period_label
from app.analytics.briefing import _date_columns, _metric_columns
from app.schemas.analysis import ToolCallRecord

_MAX_SUGGESTIONS = 3


def suggest_follow_ups(
    df: pl.DataFrame, question: str, tool_calls: list[ToolCallRecord]
) -> list[str]:
    dates = _date_columns(df)
    metrics = _metric_columns(df)
    dims = _auto_dimensions(df, exclude={*dates, *metrics})
    ok = [t for t in tool_calls if not (isinstance(t.result, dict) and t.result.get("error"))]
    out: list[str] = []

    change = next((t for t in reversed(ok) if t.tool == "explain_change"), None)
    grouped = next((t for t in reversed(ok) if t.tool == "group_by_aggregate"), None)

    if change is not None:
        r: dict[str, Any] = change.result
        metric = (r.get("metric") or {}).get("column") or "the count"
        used = [b["dimension"] for b in r.get("breakdowns", [])]
        top = next((b for b in r.get("breakdowns", []) if b.get("top_contributors")), None)
        if top:
            seg = top["top_contributors"][0]["segment"]
            when = period_label(r.get("current_period", ""), r.get("freq", "month"))
            out.append(
                f"Show the {when} rows where {top['dimension']} is {seg}, "
                "and what changed for them."
            )
        unused = [d for d in dims if d not in used]
        if unused:
            out.append(f"Break the change in {metric} down by {unused[0]}.")
        out.append(f"How has {metric} trended over the last several {r.get('freq', 'month')}s?")
    elif grouped is not None:
        args = grouped.arguments
        by = args.get("group_by") or []
        metric = args.get("column") or "row count"
        if dates and metric != "row count":
            out.append(
                f"Why did {metric} change in the latest period, and which segments drove it?"
            )
        other = [d for d in dims if d not in by]
        if other:
            out.append(
                f"Break {metric} down by {other[0]}" + (f" within each {by[0]}." if by else ".")
            )
        if by:
            out.append(f"Show the top 5 {by[0]} by {metric}.")
    else:
        if metrics and dims:
            out.append(f"Which {dims[0]} has the highest total {metrics[0]}?")
        if metrics and dates:
            out.append(f"Why did {metrics[0]} change in the latest period?")
        if metrics:
            out.append(f"Are there outliers in {metrics[0]}?")

    asked = question.strip().lower()
    return [q for q in dict.fromkeys(out) if q.lower() != asked][:_MAX_SUGGESTIONS]
